#!/usr/bin/env python3
"""Enforce the ``__init__.py`` docstring LAW and generate each folder's README.

WHY THIS SCRIPT EXISTS
    The only copy of this tool on the drive
    (``_DOCS/python-exemplar/_githooks/generate_folder_docs.py``) carries three
    verified defects, and this file is a fresh implementation rather than a
    patch of it, because a file that has never parsed has never been tested by
    anything:

    1. It is not valid Python 3. Line 68 reads ``except SyntaxError,
       UnicodeDecodeError:``, a Python 2 form that raises at PARSE time. No
       hook, no CI, and no human has ever executed it.
    2. It checks none of the four required sections. Its whole test is
       presence, a 120-character floor, and a placeholder-prefix scan -- so a
       docstring with no ``Key Components:`` at all passes.
    3. It has no write path. It generates no README, though the standard says
       "Docstring is the source. README.md is generated."

WHAT IT ENFORCES
    ``_DOCS/STANDARDS-python.md`` "LAW: every __init__.py has a full module
    docstring" names four sections, and this script requires each BY NAME at
    the start of a line: ``Key Components:``, ``Pattern/Convention:``,
    ``Example:``, ``See Also:``. Presence of the header is necessary but not
    sufficient -- each section must also carry substance beneath it, because a
    header with an empty body satisfies a naive scan while documenting nothing.

    Section rules live in the ``SECTIONS`` table, never in nested conditionals.
    Adding a required section is a row, per the flat-control-flow LAW.

WHY IT BLOCKS
    The standard states the failure mode as a law: "the generator BLOCKS. It
    does not skip." A missing docstring, one under the floor, or one lacking a
    required section fails the commit. There is no skip path and no branch that
    can reach exit 0 with a finding outstanding -- ``main`` derives its exit
    code from the finding count rather than from control flow, so a future
    early-return cannot silently turn this green.

Exit codes:
    0  every package satisfies the law; in write mode every README is current
    1  a real finding -- a docstring is missing, short, or incomplete
    3  harness error; the check could not run and told you nothing

Usage:
    uv run python scripts/generate_folder_docs.py           # write READMEs
    uv run python scripts/generate_folder_docs.py --check   # verify, no writes

See Also:
    - scripts/check_code_size.py: the sibling check, same exit-code grammar.
    - _githooks/pre-commit: the wiring that runs this on every commit.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

PACKAGE_ROOT = Path(__file__).resolve().parent.parent / "src"
"""Resolved from THIS file's location, and verified to exist before scanning.

A path derived from ``__file__`` breaks silently when the script moves: a
sibling check resolved to an empty directory after a relocation and printed
"Size OK" on every run thereafter. The existence check in ``main`` turns that
into an exit 3 instead of a false green.
"""

MIN_CHARS = 400
"""Substance floor for the whole docstring.

The exemplar used 120, which any three sentences clear. Four required sections
each carrying real content do not fit in 120 characters, so a floor that low
can never fire on a docstring that has the sections -- it only ever catches
what the section check already caught.
"""

MIN_SECTION_CHARS = 40
"""Substance floor for the body beneath one section header.

This is what stops ``Key Components:`` followed by nothing from passing. A
header with an empty body satisfies a presence scan while documenting nothing,
which is the defect the section check exists to catch.
"""

SECTIONS: tuple[str, ...] = (
    "Key Components:",
    "Pattern/Convention:",
    "Example:",
    "See Also:",
)
"""The four sections ``_DOCS/STANDARDS-python.md`` requires, checked by name.

A table, not a chain of conditionals: adding a required section is a row here
and no new branch anywhere, per the flat-control-flow LAW.
"""

PLACEHOLDERS: tuple[str, ...] = ("TODO", "FIXME", "XXX", "TBD", "Coming soon")
"""Prefixes that mark a docstring as unwritten regardless of its length."""

README_HEADER = (
    "<!-- GENERATED by scripts/generate_folder_docs.py"
    " -- edit the __init__.py docstring, never this file. -->"
)
"""Marker line every generated README opens with.

The standard says never hand-edit a generated README. Saying so in the file is
what makes that instruction reach the person who opens it.
"""


def module_docstring(path: Path) -> str | None:
    """Return a file's module docstring, or None when it has none or will not parse.

    Args:
        path: Python file to inspect.

    Returns:
        The docstring text, or None when absent, unparseable, or undecodable.
    """
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError) as exc:
        # DOCUMENTED FAIL-OPEN, reported rather than swallowed. Returning None
        # keeps the generator running over the rest of the package instead of
        # dying on one bad file -- but "unparseable" and "has no docstring" are
        # different facts that this return value flattens into one, and the
        # second is a gate failure while the first is a broken file.
        #
        # `print`, not a logger: this is a hook/CI script whose report IS
        # stdout, and no loguru sink is configured here. Without the line, a
        # file that cannot be parsed silently reads as undocumented -- or worse,
        # slips through a docstring gate on a technicality nobody can see.
        print(f"WARNING: {path} could not be parsed, treating as undocumented: {exc}")
        return None
    return ast.get_docstring(tree)


def section_body(doc: str, header: str) -> str | None:
    """Return the text beneath one section header, or None when the header is absent.

    The body runs from the header line to the next required section header or
    the end of the docstring, whichever comes first.

    Args:
        doc: Full docstring text.
        header: Section header to locate, matched at the start of a line.

    Returns:
        The body text with the header removed, or None if the header is missing.
    """
    lines = doc.splitlines()
    starts = [i for i, line in enumerate(lines) if line.strip() == header]
    if not starts:
        return None

    begin = starts[0] + 1
    others = {s for s in SECTIONS if s != header}
    ends = [i for i in range(begin, len(lines)) if lines[i].strip() in others]
    stop = ends[0] if ends else len(lines)
    return "\n".join(lines[begin:stop]).strip()


def _section_findings(header: str, body: str | None) -> list[str]:
    """Return the finding for one section, empty when that section is satisfactory.

    Args:
        header: The section header being judged.
        body: Its body text, or None when the header was absent.

    Returns:
        Zero or one reason, as a list so the caller can extend unconditionally.
    """
    if body is None:
        return [f"missing required section {header!r}"]
    if len(body) < MIN_SECTION_CHARS:
        return [f"section {header!r} has {len(body)} chars of body (minimum {MIN_SECTION_CHARS})"]
    return []


def docstring_findings(doc: str | None) -> list[str]:
    """Return every reason a docstring fails the law, empty when it passes.

    Every rule is evaluated -- the function never returns on the first failure,
    so one run reports the whole repair list instead of one item per commit.

    Args:
        doc: The module docstring, or None when the file has none.

    Returns:
        Human-readable reasons, one per violated rule.
    """
    if doc is None:
        return ["no module docstring (or the file does not parse)"]

    stripped = doc.strip()
    found: list[str] = []

    if len(stripped) < MIN_CHARS:
        found.append(f"docstring is {len(stripped)} chars (minimum {MIN_CHARS})")

    placeholders = [p for p in PLACEHOLDERS if stripped.upper().startswith(p.upper())]
    found.extend(f"docstring starts with placeholder {p!r}" for p in placeholders)

    for header in SECTIONS:
        found.extend(_section_findings(header, section_body(stripped, header)))

    return found


def readme_text(package: Path, doc: str) -> str:
    """Render the README for one package from its docstring.

    Args:
        package: The package directory the README belongs to.
        doc: The validated module docstring.

    Returns:
        Full README file content, ending in a newline.
    """
    return f"{README_HEADER}\n\n# {package.name}\n\n{doc.strip()}\n"


def scan(package_root: Path) -> list[tuple[Path, list[str]]]:
    """Judge every package under a root, returning each one's findings.

    Args:
        package_root: Directory to walk for ``__init__.py`` files.

    Returns:
        Pairs of (init path, findings); the findings list is empty on a pass.
    """
    inits = sorted(package_root.rglob("__init__.py"))
    return [(init, docstring_findings(module_docstring(init))) for init in inits]


def write_readmes(results: list[tuple[Path, list[str]]]) -> list[Path]:
    """Write the README for every package that passed, skipping none silently.

    Only passing packages are written, because a README generated from a
    docstring that violates the law would publish the violation. This function
    is unreachable while any finding stands -- ``main`` returns 1 first.

    Args:
        results: Output of ``scan``.

    Returns:
        Paths of READMEs whose content changed on disk.
    """
    changed: list[Path] = []
    for init, findings in results:
        doc = module_docstring(init)
        if findings or doc is None:
            continue
        readme = init.parent / "README.md"
        text = readme_text(init.parent, doc)
        if readme.exists() and readme.read_text(encoding="utf-8") == text:
            continue
        readme.write_text(text, encoding="utf-8")
        changed.append(readme)
    return changed


def report(results: list[tuple[Path, list[str]]], root: Path) -> int:
    """Print the verdict for every package and return the number that failed.

    Args:
        results: Output of ``scan``.
        root: Path findings are reported relative to.

    Returns:
        Count of failing packages.
    """
    failing = 0
    for init, findings in results:
        rel = init.relative_to(root)
        if not findings:
            print(f"  PASS  {rel}")
            continue
        failing += 1
        print(f"  FAIL  {rel}", file=sys.stderr)
        for reason in findings:
            print(f"          - {reason}", file=sys.stderr)
    return failing


def parse_args(argv: list[str]) -> argparse.Namespace:
    """Parse the command line strictly, exiting 2 on anything unrecognized.

    Substring matching was the defect this replaces: any argument at all put
    the script in write mode unless it happened to be ``--check``, so a typo
    like ``--chek`` -- or ``--help`` -- silently WROTE files instead of
    reporting that the flag is not a flag. ``argparse`` refuses an unknown
    argument with exit 2 and a usage line, which is the standard grammar.

    Args:
        argv: Command-line arguments after the program name.

    Returns:
        The parsed namespace, carrying ``check`` only.
    """
    parser = argparse.ArgumentParser(
        prog="generate_folder_docs.py",
        description="Enforce the __init__.py docstring LAW and generate each folder's README.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify only; report violations and write no README (default: write)",
    )
    return parser.parse_args(argv)


def main(argv: list[str]) -> int:
    """Run the check, optionally write READMEs, and return the process exit code.

    Args:
        argv: Command-line arguments after the program name.

    Returns:
        0 when everything passes, 1 on any finding, 3 on a harness error.
    """
    check_only = parse_args(argv).check

    if not PACKAGE_ROOT.is_dir():
        print(f"ERROR: package root does not exist: {PACKAGE_ROOT}", file=sys.stderr)
        print("IMPACT: nothing was examined. ACTION: fix PACKAGE_ROOT.", file=sys.stderr)
        return 3

    results = scan(PACKAGE_ROOT)
    if not results:
        print(f"ERROR: no __init__.py found under {PACKAGE_ROOT}", file=sys.stderr)
        print("IMPACT: a pass here would mean nothing. ACTION: check the path.", file=sys.stderr)
        return 3

    mode = "check" if check_only else "write"
    print(f"Docstring law ({mode} mode): {len(results)} package(s) under {PACKAGE_ROOT}")
    failing = report(results, PACKAGE_ROOT.parent)

    if failing:
        print(
            f"\nBLOCKED: {failing} of {len(results)} package(s) violate the docstring LAW.",
            file=sys.stderr,
        )
        print(
            "IMPACT: the commit is refused; generated READMEs were NOT written for these.\n"
            "ACTION REQUIRED: edit the __init__.py docstring -- never the README.\n"
            "  Required sections: " + ", ".join(SECTIONS),
            file=sys.stderr,
        )
        return 1

    if check_only:
        print(f"\nOK: {len(results)} package(s) satisfy the docstring LAW. No READMEs written.")
        return 0

    changed = write_readmes(results)
    for readme in changed:
        print(f"  WROTE {readme.relative_to(PACKAGE_ROOT.parent)}")
    print(f"\nOK: {len(results)} package(s) pass; {len(changed)} README(s) updated.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
