"""Containment for what may leave a FAILED Graph response.

Split out of ``outlook.py`` for the size ceiling. The cohesion is one
containment rule, not a grab bag: everything here decides what may travel
out of a failed Graph response and into an exception that ``ProviderCall``
logs with ``opt(exception=True)``. ``_unwrap`` stays in the adapter -- it is the
transport's own return path and calls INTO this layer rather than belonging
to it.
"""

from __future__ import annotations

import re

import httpx
from loguru import logger

from inbox_zero_connector.providers.base import ProviderError
from inbox_zero_connector.providers.retry import RETRYABLE_STATUS

MAX_ERROR_TOKEN_CHARS = 80
"""Length bound on one structured diagnostic taken from a Graph error.

A bound applies even to the fields below because they are still SERVER-
controlled: nothing stops a proxy putting prose in a field Graph documents as
a code. The bound is small on purpose -- an error code and a request id are
both short, so a value that needs more than this is not one of them.
"""

_ERROR_TOKEN = re.compile(r"\A[A-Za-z0-9_.:-]+\Z")
"""The shape a structured diagnostic must have to be carried at all.

A CLOSED shape, not a length cut, and that difference is the whole fix. Graph
error codes (``ErrorInvalidRecipients``) and request ids
(``a1b2c3d4-...``) are identifier-shaped: no spaces, no punctuation that
prose needs. Free text fails this immediately at its first space, so a
diagnostic field that a proxy filled with an echo of the request is DROPPED
rather than truncated.
"""

_REQUEST_ID_HEADERS = ("request-id", "client-request-id")
"""Headers Microsoft asks for when a Graph failure is escalated to them.

These are what actually diagnoses a Graph failure on Microsoft's side, and
they are generated by Graph rather than derived from the request payload, so
they cannot echo content.
"""


def _error_token(value: object) -> str | None:
    """One server-supplied diagnostic, or None when it is not identifier-shaped."""
    if not isinstance(value, str) or not value or len(value) > MAX_ERROR_TOKEN_CHARS:
        return None
    return value if _ERROR_TOKEN.match(value) else None


def _error_code(response: httpx.Response) -> str | None:
    """The ``error.code`` of a Graph error envelope, when it is a real code.

    Deliberately reads ONLY ``code`` and never ``message``: ``message`` is
    free prose by definition, and free prose from an upstream that just
    rejected our request is exactly where an echo of that request's body
    appears.
    """
    try:
        payload = response.json()
    except ValueError:
        # DOCUMENTED FAIL-OPEN. A non-JSON error body (an HTML proxy page, a
        # truncated response) is not an envelope and has no code. Swallowed
        # rather than raised because this function's whole job is best-effort
        # enrichment of a failure that is already being reported; a parse error
        # here must not replace it.
        #
        # DEBUG, and NO EXCERPT OF THE BODY IS LOGGED -- not even a truncated
        # one. That is the same containment rule this module exists to enforce:
        # a rejected Graph request routinely echoes the content it rejected,
        # which here is the owner's mail, and a character bound is not
        # redaction. The status is generated by Graph and is safe to name; the
        # body is not, at any length. `ProviderCall` already logs the failure
        # itself at ERROR with a traceback, so this line only explains why that
        # failure arrived without a Graph error code attached.
        logger.debug(
            f"GRAPH: error body is not a JSON envelope, no error code available "
            f"status={response.status_code}"
        )
        return None
    if not isinstance(payload, dict):
        return None
    error = payload.get("error")
    return _error_token(error.get("code")) if isinstance(error, dict) else None


def _provider_error(response: httpx.Response, method: str, path: str) -> ProviderError:
    """Build the adapter's one failure message from NON-CONTENT diagnostics only.

    Shared by ``_unwrap`` and the retry-exhaustion path so a throttled read
    that ran out of attempts reports identically to one that failed outright.

    NO EXCERPT OF THE RESPONSE BODY TRAVELS, and the reason is that a character
    bound is not redaction. This adapter POSTs the owner's draft as
    ``{"comment": body}``; Graph, a proxy, or a WAF in front of either echoes
    rejected request content back in the error payload as a matter of routine.
    Copying even 300 characters of that into a ``ProviderError`` put privileged
    mail into an exception that ``ProviderCall`` logs with ``opt(exception=True)`` --
    every sink, on disk, past the mailbox's own retention. A subject line and
    the opening of a body fit inside 300 characters comfortably, so the bound
    limited the SIZE of the leak and not the leak.

    Field-aware redaction was the other option and does not fit here: it
    matches on a field NAME, and an upstream sentence carries no names to
    match, so it would blank nothing in ``"the request body was rejected:
    <body>"``. Structured diagnostics do fit -- the status, the Graph error
    ``code``, and the ``request-id`` header are generated by Graph rather than
    derived from what we sent, and they are what Microsoft asks for when a
    failure is escalated. Each is admitted only if it is identifier-shaped, so
    a diagnostic field stuffed with prose is dropped rather than trimmed.

    ``method`` and ``path`` arrive separately rather than pre-joined because
    the path is already validated and encoded by ``_graph_path``; joining them
    here keeps the module free of any expression that formats a caller-supplied
    value next to a path literal, which is what the structural scan in
    ``tests/test_graph_provider.py`` refuses.

    Args:
        response: The failed Graph response.
        method: The HTTP verb, for the message.
        path: The request path, already validated and encoded.

    Returns:
        The failure the adapter raises, carrying no upstream free text.
    """
    parts = [f"HTTP {response.status_code}"]
    if (code := _error_code(response)) is not None:
        parts.append(f"code={code}")
    for header in _REQUEST_ID_HEADERS:
        if (request_id := _error_token(response.headers.get(header))) is not None:
            parts.append(f"{header}={request_id}")
            break
    what = " ".join((method, path))
    detail = ", ".join(parts)
    return ProviderError(
        f"Graph {what} failed with {detail} "
        "(upstream error text withheld: it can echo request content)"
    )


def _raise_if_retryable(response: httpx.Response) -> None:
    """Raise a status-bearing error when the status is worth another attempt.

    This is the bridge between httpx and ``providers/retry.py``. httpx treats
    a 429 or a 503 as a perfectly good Response and raises nothing, so the
    retry policy -- which decides from an EXCEPTION's status -- was reading a
    successful return and retrying nothing. ``HTTPStatusError`` is raised
    because ``retry._status_of`` already knows how to read
    ``exc.response.status_code`` off it; no new error type, no second table.

    Non-retryable failures are deliberately left alone: they fall through to
    ``_unwrap``, which turns them into the same bounded ``ProviderError`` as
    before. Only the transient statuses need to travel as exceptions, and only
    for as long as the retry loop is looking at them.

    Raises:
        httpx.HTTPStatusError: If the status is in ``RETRYABLE_STATUS``. This
            escapes to the caller only after the attempt budget is spent; the
            caller converts it to a ``ProviderError``.
    """
    if response.status_code in RETRYABLE_STATUS:
        raise httpx.HTTPStatusError(
            f"Graph returned HTTP {response.status_code}",
            request=response.request,
            response=response,
        )
